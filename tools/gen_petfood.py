"""Genera PetFood.lua del addon: qué come la mascota, a partir de la base de datos de cmangos (GPLv3).

Uso: python -I gen_petfood.py <ClassicDB_*.sql.gz de cmangos/classic-db> <salida PetFood.lua>
De cada objeto solo se toma el número, el tipo de comida (FoodType) y el nivel (ItemLevel).
"""
import gzip
import re
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
sql = gzip.open(src, "rt", encoding="utf-8", errors="replace").read()

create = re.search(r"CREATE TABLE `item_template` \((.*?)\n\)", sql, re.S).group(1)
columns = re.findall(r"^\s*`(\w+)`", create, re.M)
ENTRY, NAME, LEVEL, FOOD = (columns.index(c) for c in ("entry", "name", "ItemLevel", "FoodType"))

# Valores de una fila de INSERT: números, NULL o cadenas entre comillas simples con escapes
TOKEN = re.compile(r"'((?:[^'\\]|\\.)*)'|(NULL)|(-?[\d.]+(?:e-?\d+)?)")


def rows(statement):
    i = 0
    while True:
        start = statement.find("(", i)
        if start < 0:
            return
        values, j = [], start + 1
        while True:
            m = TOKEN.match(statement, j)
            if not m:
                raise ValueError(statement[j:j + 40])
            values.append(m.group(1) if m.group(1) is not None else None if m.group(2) else m.group(3))
            j = m.end()
            if statement[j] == ",":
                j += 1
            elif statement[j] == ")":
                break
        yield values
        i = j + 1


foods = []
for statement in re.findall(r"INSERT INTO `item_template` VALUES (.*?\));\n", sql, re.S):
    for v in rows(statement):
        food = int(v[FOOD])
        if 1 <= food <= 8:
            foods.append((int(v[ENTRY]), food, int(v[LEVEL]), v[NAME].replace("\\'", "'")))

lines = [
    "-- What hunter pets eat. Generated by tools/gen_petfood.py, do not edit by hand.",
    "-- Data derived from the cmangos Classic database (https://github.com/cmangos/classic-db), used under the GPLv3.",
    "-- t = food type (1 meat, 2 fish, 3 cheese, 4 bread, 5 fungus, 6 fruit, 7 raw meat, 8 raw fish),",
    "-- l = item level (a pet only eats food up to 14 levels below its own).",
    "local _, ns = ...",
    "",
    "ns.petFoods = {",
]
for entry, food, level, name in sorted(foods, key=lambda f: (f[1], f[2], f[0])):
    lines.append(f"\t[{entry}] = {{ t = {food}, l = {level} }}, -- {name}")
lines += ["}", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(foods)} comidas de mascota -> {out}")
